"""moex/tools/gen_llama_unicode.py - extract llama.cpp's Unicode class tables into tools/strata_unicode_tables.py.

WHY.  llama.cpp's pre-tokenizers do not ask a Unicode library what a code point is: they read a generated table
(src/unicode-data.cpp, made by scripts/gen-unicode-data.py from the UnicodeData.txt of the day).  The table's Unicode
version and its few conventions (C-locale `\\s` for ASCII, the Unicode White_Space set for the rest, private use and
format characters as CONTROL, unassigned as UNDEFINED) decide where a word ends, so a tokenizer that asks Python's
`regex` module for \\p{L} agrees with it only as long as both tables agree.  This copies the table instead, so the
families' pre-tokenizers (tools/strata_tokenizer_families.py) use llama.cpp's classes by construction.

    python3 moex/tools/gen_llama_unicode.py [--src ~/AI/llama.cpp-glm5next-mtp/src/unicode-data.cpp]

The output is deterministic and checked in; run this again only when the oracle's llama.cpp tree changes.
"""
from __future__ import annotations
import os as _os  # moex: paths from this checkout's place (moex/README.md, Paths)
_REPO = _os.path.abspath(_os.path.join(_os.path.dirname(_os.path.abspath(__file__)), '../..'))
_AI = _os.environ.get("STRATA_AI_DIR") or _os.path.dirname(_REPO)

import argparse
import hashlib
import pathlib
import re
import subprocess

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent.parent / "tools" / "strata_unicode_tables.py"
DEFAULT_SRC = pathlib.Path(_os.path.join(_AI, 'llama.cpp-glm5next-mtp/src/unicode-data.cpp'))

FLAG_NAMES = {0x0001: "UNDEFINED", 0x0002: "NUMBER", 0x0004: "LETTER", 0x0008: "SEPARATOR", 0x0010: "MARK",
              0x0020: "PUNCTUATION", 0x0040: "SYMBOL", 0x0080: "CONTROL"}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default=str(DEFAULT_SRC))
    ap.add_argument("--out", default=str(OUT))
    a = ap.parse_args()
    src_path = pathlib.Path(a.src)
    text = src_path.read_text(encoding="utf-8")
    m = re.search(r"unicode_ranges_flags = \{[^\n]*\n(.*?)\n\};", text, re.S)
    ranges = [(int(s, 16), int(f, 16)) for s, f in re.findall(r"\{0x([0-9A-Fa-f]+), 0x([0-9A-Fa-f]+)\}", m.group(1))]
    assert ranges[0][0] == 0 and ranges[-1][0] == 0x110000, (ranges[0], ranges[-1])
    m = re.search(r"unicode_set_whitespace = \{(.*?)\n\};", text, re.S)
    white = sorted(int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]+)", m.group(1)))
    m = re.search(r"unicode_map_lowercase = \{[^\n]*\n(.*?)\n\};", text, re.S)
    lower = [(int(a_, 16), int(b_, 16)) for a_, b_ in re.findall(r"\{0x([0-9A-Fa-f]+), 0x([0-9A-Fa-f]+)\}", m.group(1))]
    sha = hashlib.sha256(src_path.read_bytes()).hexdigest()
    try:
        head = subprocess.run(["git", "-C", str(src_path.parent.parent), "rev-parse", "HEAD"], capture_output=True,
                              text=True, check=True).stdout.strip()
    except Exception:
        head = "unknown"
    # one flag word per RANGE, as (start, flags): the category in the low byte
    flat = ", ".join("(%d, %d)" % (s, f) for s, f in ranges)
    wrapped = []
    line = "    "
    for item in flat.split("), ") :
        item = item if item.endswith(")") else item + ")"
        if len(line) + len(item) + 2 > 118:
            wrapped.append(line.rstrip())
            line = "    "
        line += item + ", "
    wrapped.append(line.rstrip())
    body = "\n".join(wrapped)
    out = pathlib.Path(a.out)
    out.write_text(f'''"""tools/strata_unicode_tables.py - llama.cpp's Unicode class tables (GENERATED: do not edit).

Generated by moex/tools/gen_llama_unicode.py from {src_path.name}
  llama.cpp HEAD {head}
  sha256 {sha}

RANGES is [(first code point, flags), ...] with a final (0x110000, 0) sentinel; a range ends where the next begins.
FLAGS are llama.cpp's unicode_cpt_flags category bits: {", ".join("0x%04x %s" % (k, v) for k, v in FLAG_NAMES.items())}.
WHITESPACE is the Unicode White_Space set (NOT str.isspace: U+001C..U+001F are not in it).  LOWER_TO_ASCII is the set of
code points whose llama.cpp lowercase is one of the contraction letters s t m d r e v l (the pre-tokenizers lower-case the
letter after an apostrophe).
"""
RANGES = [
{body}
]
WHITESPACE = {tuple(white)!r}
LOWER_TO_ASCII = {tuple(sorted(c for c, l in lower if l in set(map(ord, "stmdrevl"))))!r}
''', encoding="utf-8")
    print("wrote", out, len(ranges), "ranges,", len(white), "whitespace code points")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
