#!/usr/bin/env python3
"""moex/tools/gen_geometry.py - moex/models/*.json -> moex/generated/moex_geometry.hpp: one constexpr geometry per
target, next to Strata's hard-coded ModelGeometry (include/strata/core/layout.hpp), so the engine port starts from
generated numbers instead of hand-copied ones.  usage: gen_geometry.py [--models moex/models] [--out ...hpp]"""
import argparse, glob, json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ATTN = {"qwen4_exp_text": "kGdnQsa", "glm5_next_text": "kKdaDsa", "deepseek_v4": "kCompressedSparse", "mimo_v2": "kSwaGqa"}
RES = {"low-rank (Qwen)": "kHcLowRank", "Sinkhorn (mHC)": "kHcSinkhorn", None: "kPlain"}
def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--models", default=os.path.join(ROOT, "models"))
    ap.add_argument("--out", default=os.path.join(ROOT, "generated", "moex_geometry.hpp")); a = ap.parse_args()
    out = ["// moex/generated/moex_geometry.hpp - GENERATED by moex/tools/gen_geometry.py from config.json; do not edit.",
           "#pragma once", "#include <cstdint>", "", "namespace moex {", "",
           "enum class AttnFamily { kGdnQsa, kKdaDsa, kCompressedSparse, kSwaGqa };",
           "enum class Residual { kHcLowRank, kHcSinkhorn, kPlain };",
           "enum class Scoring { kSoftmax, kSigmoid, kSqrtSoftplus };", "",
           "struct MoeGeometry {", "    const char* model_type;", "    int64_t n_embd, n_layers, moe_layers, dense_layers;",
           "    int64_t n_expert, top_k, n_ff_expert, n_shared, n_ff_shared;", "    Scoring scoring;",
           "    AttnFamily attention;", "    Residual residual;", "    int64_t hc_streams, mtp_layers;",
           "    bool ngram_ple, vision;", "    constexpr int64_t expert_params() const { return 3 * n_embd * n_ff_expert; }",
           "    constexpr int64_t routed_active_params() const { return expert_params() * top_k * moe_layers; }", "};", ""]
    sc = {"softmax": "kSoftmax", "sigmoid": "kSigmoid", "sqrtsoftplus": "kSqrtSoftplus"}
    for f in sorted(glob.glob(os.path.join(a.models, "*.json"))):
        d = json.load(open(f)); m = d["moe"]; hc = d["hyper_connections"] or {}
        name = "k" + "".join(p.capitalize() for p in d["model_type"].replace("-", "_").split("_"))
        out.append(f"inline constexpr MoeGeometry {name}{{\"{d['model_type']}\", {d['hidden']}, {d['layers']}, {m['moe_layers']}, "
                   f"{m['dense_layers']}, {m['routed_experts']}, {m['top_k']}, {m['expert_intermediate']}, {m['shared_experts']}, "
                   f"{m['shared_intermediate']}, Scoring::{sc.get(m['scoring'], 'kSoftmax')}, AttnFamily::{ATTN[d['model_type']]}, "
                   f"Residual::{RES[hc.get('kind')]}, {hc.get('streams') or 0}, {d['mtp_layers']}, {str(d['ngram_ple']).lower()}, "
                   f"{str(d['vision']).lower()}}};")
    out += ["", "}  // namespace moex", ""]
    os.makedirs(os.path.dirname(a.out), exist_ok=True); open(a.out, "w").write("\n".join(out)); print("wrote", a.out)
if __name__ == "__main__":
    main()
